class SyncTest(unittest.TestCase):
    def test_up_to_date_then_second_parent(self):
        repo, root = make_minimal({"notes.txt": "first\n"})
        upstream = repo.git("rev-parse", "upstream/master").stdout.decode().strip()

        first = run_script(repo, "sync", "--trailer", "Signed-off-by: Test <t@e>")
        self.assertEqual(first.returncode, 0, first.stderr.decode())
        payload = last_json(first)
        tip = payload["branch"]["sha"]
        self.assertEqual(payload["branch"]["name"], "upstream-renamed")
        self.assertTrue(tip)
        parents = repo.git(
            "rev-list", "--parents", "-n", "1", "upstream-renamed"
        ).stdout.decode().split()
        self.assertEqual(parents[1:], [upstream])
        message = repo.git(
            "log", "-1", "--format=%B", "upstream-renamed"
        ).stdout.decode()
        self.assertIn("Signed-off-by: Test <t@e>\n", message)
        count_after_first = repo.git(
            "rev-list", "--count", "upstream-renamed"
        ).stdout

        second = run_script(repo, "sync")
        self.assertEqual(second.returncode, 0, second.stderr.decode())
        self.assertIn(b"up to date", second.stderr)
        self.assertEqual(
            repo.git("rev-parse", "upstream-renamed").stdout.decode().strip(), tip
        )
        self.assertEqual(
            repo.git("rev-list", "--count", "upstream-renamed").stdout,
            count_after_first,
        )

        repo.write("notes.txt", "second\n")
        repo.git("add", "-A")
        repo.git("commit", "-q", "-m", "next upstream")
        new_upstream = repo.git("rev-parse", "HEAD").stdout.decode().strip()
        repo.git("update-ref", "refs/heads/upstream/master", new_upstream)

        third = run_script(repo, "sync")
        self.assertEqual(third.returncode, 0, third.stderr.decode())
        new_tip = last_json(third)["branch"]["sha"]
        self.assertNotEqual(new_tip, tip)
        parents = repo.git(
            "rev-list", "--parents", "-n", "1", "upstream-renamed"
        ).stdout.decode().split()
        self.assertEqual(parents[1:], [tip, new_upstream])

    def test_refuses_checked_out_branch(self):
        repo, root = make_minimal({"notes.txt": "first\n"})
        head_before = repo.git("rev-parse", "HEAD").stdout
        result = run_script(repo, "sync", "--branch", "main")
        self.assertEqual(result.returncode, 1)
        self.assertIn(b"checked out", result.stderr)
        self.assertEqual(repo.git("rev-parse", "HEAD").stdout, head_before)
        self.assertEqual(repo.git("rev-parse", "refs/heads/main").stdout, head_before)

    def test_runs_from_a_subdirectory(self):
        repo, root = make_minimal({"notes.txt": "first\n"})
        nested = os.path.join(root, "docs", "deep")
        os.makedirs(nested)
        result = run_script(repo, "check", cwd=nested)
        self.assertEqual(result.returncode, 0, result.stderr.decode())
        self.assertEqual(last_json(result)["problems_total"], 0)


