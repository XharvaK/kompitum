class Repo:
    def __init__(self, root):
        self.root = root

    def git(self, *args, input=None, check=True):
        command = [
            "git",
            "-c",
            "user.name=Test",
            "-c",
            "user.email=test@example.com",
            "-c",
            "core.autocrlf=false",
            "-c",
            "core.safecrlf=false",
        ] + list(args)
        result = subprocess.run(
            command,
            cwd=self.root,
            input=input,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            creationflags=NO_WINDOW,
            env=BASE_ENV,
        )
        if check and result.returncode:
            raise AssertionError(
                "git %s failed: %s"
                % (" ".join(args), result.stderr.decode("utf-8", "replace"))
            )
        return result

    def write(self, path, data):
        full = os.path.join(self.root, path)
        parent = os.path.dirname(full)
        if parent:
            os.makedirs(parent, exist_ok=True)
        if isinstance(data, str):
            data = data.encode("utf-8")
        with open(full, "wb") as handle:
            handle.write(data)

    def read(self, ref, path):
        return self.git("show", "%s:%s" % (ref, path)).stdout


def run_script(repo, *args, env=None, cwd=None):
    full_env = dict(BASE_ENV)
    if env:
        full_env.update(env)
    return subprocess.run(
        [sys.executable, "-B", SCRIPT] + list(args),
        cwd=cwd or repo.root,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        creationflags=NO_WINDOW,
        env=full_env,
    )


def last_json(result):
    lines = result.stdout.decode("utf-8", "replace").strip().splitlines()
    return json.loads(lines[-1])


def tree_map(repo, ref):
    entries = {}
    output = repo.git("ls-tree", "-r", ref).stdout.decode("utf-8")
    for line in output.splitlines():
        meta, path = line.split("\t", 1)
        mode, kind, oid = meta.split(" ")
        entries[path] = (mode, kind, oid)
    return entries


def make_repo(files):
    root = tempfile.mkdtemp(prefix="limenize-test-")
    TEMP_DIRS.append(root)
    repo = Repo(root)
    repo.git("init", "-q")
    repo.git("checkout", "-q", "-b", "main")
    for path, data in files.items():
        repo.write(path, data)
    repo.git("add", "-A")
    repo.git("commit", "-q", "-m", "upstream")
    return repo, root


def add_upstream_ref(repo):
    repo.git("update-ref", "refs/heads/upstream/master", "HEAD")


def make_minimal(extra=None):
    files = {
        "scripts/notices": limenize.OLD_LICENSE + " It includes the software below.\n",
        "crates/herdr-core/THIRD-PARTY-NOTICES": limenize.OLD_LICENSE
        + " It includes Ghostty.\n",
        "docs/keep.txt": "nothing to rename\n",
    }
    if extra:
        files.update(extra)
    repo, root = make_repo(files)
    add_upstream_ref(repo)
    return repo, root


class TextRulesTest(unittest.TestCase):
    CASES = [
        ("releases.herdr.dev", "releases.limen.invalid"),
        ("herdr", "limen"),
        ("herdr_core", "limen_core"),
        ("Herdr", "Limen"),
        ("Herdr Core.app", "Limen Core.app"),
        ("HERDR", "LIMEN"),
        ("HERDR_RELEASES_URL", "LIMEN_RELEASES_URL"),
        ("nohc", "nolc"),
        ("hc", "lc"),
        ("HC", "LC"),
        ("hcs", "lcs"),
        ("still_hcs", "still_lcs"),
        ("hc_missing", "lc_missing"),
        ("HC_SCOPE", "LIMEN_SCOPE"),
        ("$HC_TERMINAL_ID", "$LIMEN_TERMINAL_ID"),
        ("$env:HC_SSH", "$env:LIMEN_SSH"),
        ("WINDOWS_HC", "WINDOWS_LC"),
        ("dev.herdr.core", "dev.limen.core"),
        ("CARGO_BIN_EXE_herdr-core", "CARGO_BIN_EXE_limen-core"),
        (
            'kind(&["add", "nohc"]), "hc_missing"',
            'kind(&["add", "nolc"]), "lc_missing"',
        ),
        ("__hc_prompt", "__lc_prompt"),
        ("try_hc", "try_lc"),
        ("--hc-launchd", "--lc-launchd"),
        ("/var/tmp/hc-test-", "/var/tmp/lc-test-"),
        ("s.hc(", "s.lc("),
    ]

    def test_table(self):
        for old, new in self.CASES:
            with self.subTest(old=old):
                self.assertEqual(limenize.apply_text(old), new)

    def test_escape_edge(self):
        source = '"sh' + chr(92) + 'nhc ls"'
        expected = '"sh' + chr(92) + 'nlc ls"'
        self.assertEqual(limenize.apply_text(source), expected)

    def test_escape_token(self):
        tokens = {}
        source = '"sh' + chr(92) + 'nhc ls"'
        limenize.apply_text(source, tokens)
        self.assertEqual(tokens["nhc"], {"new": "nlc", "count": 1})

    def test_no_change(self):
        for value in (
            "LC_ALL",
            "libc::LC_CTYPE_MASK",
            "hcl",
            "chc",
            "hc2",
            "OSC 7501",
            "NOT_HERE",
        ):
            with self.subTest(value=value):
                self.assertEqual(limenize.apply_text(value), value)

    def test_idempotent(self):
        for old, new in self.CASES:
            with self.subTest(old=old):
                self.assertEqual(limenize.apply_text(new), new)
        sentence = (
            "hc Herdr HERDR hcs HC_SCOPE releases.herdr.dev nohc "
            'hc_missing "sh' + chr(92) + 'nhc ls"'
        )
        once = limenize.apply_text(sentence)
        self.assertEqual(limenize.apply_text(once), once)


