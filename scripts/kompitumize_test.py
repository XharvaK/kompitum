class RustfmtTest(unittest.TestCase):
    @unittest.skipUnless(HAVE_RUSTFMT, "rustfmt not installed")
    def test_real_rustfmt_reorders(self):
        repo, root = make_repo(
            {
                "scripts/notices": kompitumize.OLD_LICENSE + "\n",
                "crates/herdr-core/THIRD-PARTY-NOTICES": kompitumize.OLD_LICENSE + "\n",
                "crates/herdr-core/src/thing.rs": (
                    "use herdr_core::a; use json::x;\nuse log::b;\n"
                ),
                "rustfmt.toml": "max_width = 100\n",
            }
        )
        add_upstream_ref(repo)
        result = run_script(repo, "sync")
        self.assertEqual(result.returncode, 0, result.stderr.decode())
        self.assertEqual(
            repo.read("upstream-renamed", "crates/kompitum-core/src/thing.rs"),
            b"use json::x;\nuse kompitum_core::a;\nuse log::b;\n",
        )
        self.assertEqual(last_json(result)["counts"]["formatted"], 1)

    @unittest.skipUnless(HAVE_RUSTFMT, "rustfmt not installed")
    def test_crlf_rust_file_stays_crlf(self):
        repo, root = make_repo(
            {
                "scripts/notices": kompitumize.OLD_LICENSE + "\n",
                "crates/herdr-core/THIRD-PARTY-NOTICES": kompitumize.OLD_LICENSE + "\n",
                "crates/herdr-core/src/crlf.rs": b"use herdr_core::a;\r\nuse log::b;\r\n",
                "rustfmt.toml": "max_width = 100\n",
            }
        )
        add_upstream_ref(repo)
        result = run_script(repo, "sync")
        self.assertEqual(result.returncode, 0, result.stderr.decode())
        data = repo.read("upstream-renamed", "crates/kompitum-core/src/crlf.rs")
        self.assertIn(b"kompitum_core", data)
        self.assertIn(b"\r\n", data)
        self.assertNotIn(b"\n", data.replace(b"\r\n", b""))

