class RustfmtTest(unittest.TestCase):
    @unittest.skipUnless(HAVE_RUSTFMT, "rustfmt not installed")
    def test_real_rustfmt_reorders(self):
        repo, root = make_repo(
            {
                "scripts/notices": limenize.OLD_LICENSE + "\n",
                "crates/herdr-core/THIRD-PARTY-NOTICES": limenize.OLD_LICENSE + "\n",
                "crates/herdr-core/src/thing.rs": (
                    "use herdr_core::a; use json::x;\nuse log::b;\n"
                ),
                "rustfmt.toml": "max_width = 100\n",
            }
        )
        add_upstream_ref(repo)
        result = run_script(repo, "sync")
        self.assertEqual(result.returncode, 0, result.stderr.decode())
        self.assertEqual(
            repo.read("upstream-renamed", "crates/limen-core/src/thing.rs"),
            b"use json::x;\nuse limen_core::a;\nuse log::b;\n",
        )
        self.assertEqual(last_json(result)["counts"]["formatted"], 1)

    @unittest.skipUnless(HAVE_RUSTFMT, "rustfmt not installed")
    def test_crlf_rust_file_stays_crlf(self):
        repo, root = make_repo(
            {
                "scripts/notices": limenize.OLD_LICENSE + "\n",
                "crates/herdr-core/THIRD-PARTY-NOTICES": limenize.OLD_LICENSE + "\n",
                "crates/herdr-core/src/crlf.rs": b"use herdr_core::a;\r\nuse log::b;\r\n",
                "rustfmt.toml": "max_width = 100\n",
            }
        )
        add_upstream_ref(repo)
        result = run_script(repo, "sync")
        self.assertEqual(result.returncode, 0, result.stderr.decode())
        data = repo.read("upstream-renamed", "crates/limen-core/src/crlf.rs")
        self.assertIn(b"limen_core", data)
        self.assertIn(b"\r\n", data)
        self.assertNotIn(b"\n", data.replace(b"\r\n", b""))

    def test_missing_binary_is_a_problem(self):
        repo, root = make_repo(
            {
                "scripts/notices": limenize.OLD_LICENSE + "\n",
                "crates/herdr-core/THIRD-PARTY-NOTICES": limenize.OLD_LICENSE + "\n",
                "crates/herdr-core/src/thing.rs": "use herdr_core::a;\n",
            }
        )
        add_upstream_ref(repo)
        missing = os.path.join(root, "no-such-rustfmt")
        result = run_script(repo, "check", env={"RUSTFMT": missing})
        self.assertEqual(result.returncode, 1)
        payload = last_json(result)
        self.assertTrue(
            any(
                problem.startswith("crates/limen-core/src/thing.rs:0:")
                and "rustfmt" in problem
                for problem in payload["problems"]
            ),
            payload["problems"],
        )


class ProblemsTest(unittest.TestCase):
    def problem_for(self, files, expected, line=1, path="notes.txt"):
        repo, root = make_minimal(files)
        result = run_script(repo, "check")
        self.assertEqual(result.returncode, 1, result.stderr.decode())
        payload = last_json(result)
        prefix = "%s:%d:" % (path, line)
        matches = [problem for problem in payload["problems"] if problem.startswith(prefix)]
        self.assertTrue(matches, payload["problems"])
        self.assertTrue(any(expected in problem for problem in matches), matches)
        return repo, payload

    def test_herdrdev_is_wrong_mapping(self):
        self.problem_for({"notes.txt": "one\nherdrdev\n"}, "wrong mapping", line=2)

    def test_reserved(self):
        self.problem_for({"notes.txt": "HC_VAULT=1\n"}, "reserved")

    def test_collision(self):
        self.problem_for({"notes.txt": "an lc word\n"}, "collision")

    def test_glued_leftover(self):
        self.problem_for({"notes.txt": "xhc\n"}, "leftover")

    def test_binary_with_herdr(self):
        self.problem_for({"bad.bin": b"\x00herdr\x00"}, "binary contains", line=0, path="bad.bin")

    def test_missing_licence_line(self):
        repo, root = make_minimal()
